"""Milestone 3 sanity checks: the body driven by hand-coded controllers.

    uv run python scripts/oscillator_demo.py

Writes reports/oscillator/{oscillator.md, oscillator.json, gaits.png, chemotaxis.png}.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from wormbrain.controllers import GradientSteering, TravelingWave  # noqa: E402
from wormbrain.env import (  # noqa: E402
    Field,
    load_env_config,
    make_body,
    reward,
    run_episode,
    start_positions,
)

OUT = Path("reports/oscillator")
ARENAS = {
    "gaussian": ["configs/env.yaml"],
    "two_peaks": ["configs/env.yaml", "configs/env_two_peaks.yaml"],
    "linear": ["configs/env.yaml", "configs/env_linear.yaml"],
}
N_WORMS, SEED = 32, 0


def gaits(cfg):
    body, field = make_body(cfg["body"]), Field(cfg["field"])
    cases = {
        "forward": TravelingWave(),
        "backward": TravelingWave(direction=-1),
        "dorsal bias 0.3": TravelingWave(bias=0.3),
        "ventral bias 0.3": TravelingWave(bias=-0.3),
    }
    fig, ax = plt.subplots(figsize=(8, 5.5))
    summary = {}
    for (name, ctrl), color in zip(cases.items(), ["C0", "C1", "C2", "C3"], strict=True):
        ep = run_episode(ctrl, field, [[0, 0]], [np.pi / 2], duration=30.0, body=body,
                         record_shapes=True)  # fmt: skip
        c = ep.centroid[:, 0]
        ax.plot(c[:, 0], c[:, 1], color=color, label=name)
        for k in range(0, len(ep.t), 50):
            ax.plot(*ep.nodes[k, 0].T, color=color, lw=2, alpha=0.5)
        k5 = np.searchsorted(ep.t, 5.0)
        d = c[-1] - c[k5]
        summary[name] = {
            "speed_mm_s": float(np.linalg.norm(np.diff(c[k5:], axis=0), axis=1).sum() / 25.0),
            "net_forward_mm_s": float(d[1] / 25.0),
        }
    ax.set_aspect("equal")
    ax.set_xlim(-6, 6)
    ax.set_xlabel("x (mm)")
    ax.set_ylabel("y (mm)")
    ax.set_title("Hand-coded travelling wave, 30 s, start facing up at (0, 0)")
    ax.legend(frameon=False, fontsize=8, loc="upper right")
    fig.tight_layout()
    fig.savefig(OUT / "gaits.png", dpi=130)
    plt.close(fig)
    return summary


def chemotaxis():
    results = {}
    fig, axes = plt.subplots(1, 3, figsize=(15, 5))
    for ax, (arena, paths) in zip(axes, ARENAS.items(), strict=True):
        cfg = load_env_config(*paths)
        body, field = make_body(cfg["body"]), Field(cfg["field"])
        head, heading = start_positions(cfg["start"], field, N_WORMS, SEED)
        g = np.linspace(-15, 15, 200)
        xx, yy = np.meshgrid(g, g)
        ax.contourf(xx, yy, field.conc(np.stack([xx, yy], -1)), levels=20, cmap="Greens")
        results[arena] = {}
        for name, ctrl, color in [
            ("blind crawling", TravelingWave(), "C1"),
            ("gradient steering", GradientSteering(), "C0"),
        ]:
            ep = run_episode(ctrl, field, head, heading, body=body, **cfg["episode"])
            r = reward(ep, field, cfg["reward"])
            dist = np.linalg.norm(ep.centroid[-1] - field.center, axis=1)
            results[arena][name] = {
                "reward_mean": float(r.mean()),
                "reward_sd": float(r.std()),
                # a linear gradient has no peak to measure distance to
                "final_distance_mm_mean": None if field.kind == "linear" else float(dist.mean()),
            }
            for p in range(8):
                ax.plot(*ep.centroid[:, p].T, color=color, lw=0.8,
                        label=name if p == 0 else None)  # fmt: skip
        ax.plot(*head[:8].T, "k.", ms=4)
        ax.set_xlim(-15, 15)
        ax.set_ylim(-15, 15)
        ax.set_aspect("equal")
        ax.set_title(f"{arena}: 8 of {N_WORMS} worms, {cfg['episode']['duration']:.0f} s")
    axes[0].legend(frameon=False, fontsize=8, loc="lower left")
    fig.tight_layout()
    fig.savefig(OUT / "chemotaxis.png", dpi=110)
    plt.close(fig)
    return results


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    cfg = load_env_config("configs/env.yaml")
    gait = gaits(cfg)
    chemo = chemotaxis()
    (OUT / "oscillator.json").write_text(json.dumps({"gaits": gait, "chemotaxis": chemo}, indent=1))
    lines = [
        "# Body sanity checks (milestone 3)",
        "",
        "Generated by `scripts/oscillator_demo.py`. No connectome yet: hand-coded controllers.",
        "",
        "## Gaits (after a 5 s start-up)",
        "",
        "| controller | path speed (mm/s) | net speed along start heading (mm/s) |",
        "|---|---|---|",
    ]
    lines += [
        f"| {k} | {v['speed_mm_s']:.3f} | {v['net_forward_mm_s']:+.3f} |" for k, v in gait.items()
    ]
    lines += [
        "",
        "![gaits](gaits.png)",
        "",
        f"## Chemotaxis baselines ({N_WORMS} worms, seed {SEED})",
        "",
        "Reward: concentration gain (final 10% of the episode minus start), mean ± SD;",
        "divided by peak height for peaked fields, raw for the linear one (slope 0.1/mm).",
        "Gradient steering is a deliberately crude reference (turn while concentration",
        "falls, always the same way); in the linear field it often settles sideways.",
        "",
        "| arena | controller | reward | final distance to main peak (mm) |",
        "|---|---|---|---|",
    ]
    for arena, rows in chemo.items():
        for name, v in rows.items():
            dist = v["final_distance_mm_mean"]
            lines.append(
                f"| {arena} | {name} | {v['reward_mean']:+.3f} ± {v['reward_sd']:.3f} "
                f"| {'n/a' if dist is None else f'{dist:.1f}'} |"
            )
    lines += ["", "![chemotaxis](chemotaxis.png)", ""]
    (OUT / "oscillator.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
