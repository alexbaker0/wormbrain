"""Milestone 6 report: the pre-registered comparison of real, rewired and random wiring.

    uv run python scripts/report.py [--results reports/comparison]     (or: make report)

Follows ANALYSIS_PLAN.md. Reads <results>/runs/*.json (one file per finished run) and
writes <results>/RESULTS.md and figures. Works on partial results; the report says how
many runs it is based on.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from wormbrain.stats import bootstrap_ci, holm, stratified_permutation  # noqa: E402

GRAPHS = ("real", "rewired", "random")
SIGNS = ("excitatory", "inhibitory")
ARENAS = ("gaussian", "far_start", "two_peaks", "linear")


def load(results_dir: Path) -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted((results_dir / "runs").glob("*.json"))]


def outcome(r, arena="gaussian"):
    return r["test"][arena]["brain"]["reward_mean"]


def cells(runs, graph, key=outcome):
    """{glutamate: array of per-run values} for one graph."""
    return {g: np.array([key(r) for r in runs if r["condition"] == graph and r["glutamate"] == g])
            for g in SIGNS}  # fmt: skip


def fmt_cell(vals):
    return ", ".join(f"{v:+.2f}" for v in vals) if len(vals) else "—"


def figures(runs, out: Path):
    fig, axes = plt.subplots(1, 2, figsize=(12, 4))
    for k, graph in enumerate(GRAPHS):
        for j, glu in enumerate(SIGNS):
            vals = cells(runs, graph)[glu]
            x = (
                k
                + (j - 0.5) * 0.25
                + np.random.default_rng(k * 2 + j).uniform(-0.04, 0.04, len(vals))
            )
            axes[0].scatter(x, vals, color=f"C{j}", label=f"glutamate {glu}" if k == 0 else None)
        allv = np.concatenate(list(cells(runs, graph).values()))
        if len(allv):
            axes[0].hlines(allv.mean(), k - 0.3, k + 0.3, color="k")
    axes[0].set_xticks(range(len(GRAPHS)), GRAPHS)
    axes[0].axhline(0, color="0.7", lw=0.8)
    axes[0].set_ylabel("test reward, training arena (per run)")
    axes[0].set_title("Each dot is one training run; bar = mean")
    axes[0].legend(frameon=False, fontsize=8)
    for k, graph in enumerate(GRAPHS):
        curves = [np.maximum.accumulate(r["curve"]) for r in runs if r["condition"] == graph]
        if not curves:
            continue
        c = np.array(curves)
        axes[1].plot(c.mean(0), color=f"C{k + 2}", label=f"{graph} (n={len(c)})")
        axes[1].fill_between(np.arange(c.shape[1]), np.percentile(c, 25, 0),
                             np.percentile(c, 75, 0), color=f"C{k + 2}", alpha=0.15)  # fmt: skip
    axes[1].set_xlabel("chemotaxis generation")
    axes[1].set_ylabel("best training reward so far")
    axes[1].set_title("Learning curves: mean and interquartile range")
    axes[1].legend(frameon=False, fontsize=8)
    fig.tight_layout()
    fig.savefig(out / "comparison.png", dpi=120)
    plt.close(fig)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--results", default="reports/comparison")
    args = p.parse_args()
    out = Path(args.results)
    runs = load(out)
    planned = len(GRAPHS) * len(SIGNS) * 4
    lines = [
        "# Results: real vs rewired vs random wiring",
        "",
        f"Generated by `scripts/report.py` from {len(runs)} of {planned} planned runs, "
        "following [ANALYSIS_PLAN.md](../../ANALYSIS_PLAN.md). Outcome: mean test reward "
        "over 32 held-out starts in the training arena.",
        "",
    ]
    if len(runs) < planned:
        lines += [f"**Partial: {planned - len(runs)} runs still to come. Nothing here is final.**",
                  ""]  # fmt: skip

    lines += ["## Per-run outcomes", "", "| graph | glutamate excitatory | glutamate inhibitory "
              "| mean | runs |", "|---|---|---|---|---|"]  # fmt: skip
    for graph in GRAPHS:
        c = cells(runs, graph)
        allv = np.concatenate(list(c.values()))
        mean = f"{allv.mean():+.3f}" if len(allv) else "—"
        lines.append(f"| {graph} | {fmt_cell(c['excitatory'])} | {fmt_cell(c['inhibitory'])} "
                     f"| {mean} | {len(allv)} |")  # fmt: skip

    lines += ["", "## Primary test (pre-registered)", "",
              "Two-sided exact permutation test, labels permuted within glutamate setting; "
              "Holm-corrected over the two comparisons; 95% bootstrap interval of the "
              "difference.", "",
              "| comparison | difference (real − control) | 95% interval | p | Holm p "
              "| relabellings |",
              "|---|---|---|---|---|---|"]  # fmt: skip
    real = cells(runs, "real")
    tests = []
    for ctrl in ("rewired", "random"):
        c = cells(runs, ctrl)
        if any(len(real[s]) and len(c[s]) for s in SIGNS):
            d, pval, n = stratified_permutation(real, c)
            lo, hi = bootstrap_ci(real, c)
            tests.append((ctrl, d, lo, hi, pval, n))
    adj = holm([t[4] for t in tests]) if tests else []
    for (ctrl, d, lo, hi, pval, n), pa in zip(tests, adj, strict=True):
        lines.append(f"| real vs {ctrl} | {d:+.3f} | [{lo:+.3f}, {hi:+.3f}] | {pval:.3f} "
                     f"| {pa:.3f} | {n} |")  # fmt: skip

    lines += ["", "## Secondary outcomes", "", "### Within each glutamate setting", "",
              "| comparison | glutamate | difference | p (exact, unadjusted) |",
              "|---|---|---|---|"]  # fmt: skip
    for ctrl in ("rewired", "random"):
        c = cells(runs, ctrl)
        for s in SIGNS:
            if len(real[s]) and len(c[s]):
                d, pval, _ = stratified_permutation(
                    {k: (real[k] if k == s else np.array([])) for k in SIGNS},
                    {k: (c[k] if k == s else np.array([])) for k in SIGNS})  # fmt: skip
                lines.append(f"| real vs {ctrl} | {s} | {d:+.3f} | {pval:.3f} |")

    def reached(r):
        return r["test"]["gaussian"]["brain"].get("reached_1mm", 0.0) >= 0.5

    def climbed(r):
        return r["test"]["gaussian"]["brain"]["climbed_fraction"]

    def auc(r):
        return float(np.mean(np.maximum.accumulate(r["curve"])))

    lines += ["", "### Success, generalisation, learning speed and crawling", "",
              "| graph | runs reaching food (≥ half of starts within 1 mm) | starts climbed "
              "| far start | two peaks | linear | learning-curve area | crawl stage > 0.05 mm/s |",
              "|---|---|---|---|---|---|---|---|"]  # fmt: skip
    for graph in GRAPHS:
        rs = [r for r in runs if r["condition"] == graph]
        if not rs:
            continue
        gen = [np.mean([outcome(r, a) for r in rs]) for a in ARENAS[1:]]
        lines.append(
            f"| {graph} | {sum(map(reached, rs))}/{len(rs)} "
            f"| {np.mean([climbed(r) for r in rs]):.0%} "
            + " ".join(f"| {g:+.3f}" for g in gen)
            + f" | {np.mean([auc(r) for r in rs]):+.3f} "
            f"| {sum(r['stage1_speed_mm_s'] > 0.05 for r in rs)}/{len(rs)} |"
        )
    lines += ["", "Sensor-lesion check (secondary outcome 6): `scripts/chemotaxis_figure.py "
              f"--results {args.results}` writes `sensor_lesion.md`.", "",
              "## Caveats fixed in advance", "",
              "- 8 runs per graph can only detect large differences; a non-significant "
              "result means no detectable difference at this sample size.",
              "- In rewired and random graphs nearly every sensory neuron connects directly "
              "to a motor neuron (88% in the real graph), which may make them easier to train.",
              "", "![comparison](comparison.png)", ""]  # fmt: skip
    figures(runs, out)
    (out / "RESULTS.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
