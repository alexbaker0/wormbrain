"""Paths of trained worms, and a check that they really use the salt sensors.

    uv run python scripts/chemotaxis_figure.py [--results reports/chemotaxis_pilot_tanh]

For every run in <results>/runs/*.json (or <results>/results.json): test-set paths in
the training arena, and the same brain with ASEL and ASER silenced (lesioned). If the worm climbs by sensing
salt, silencing the sensors should abolish chemotaxis. Writes
<results>/trajectories.png and <results>/sensor_lesion.md.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from wormbrain.brain import Brain, BrainConfig, BrainController  # noqa: E402
from wormbrain.chemotaxis import env_config, load_run_config  # noqa: E402
from wormbrain.connectome import build_connectome, load_config  # noqa: E402
from wormbrain.controls import make_condition  # noqa: E402
from wormbrain.env import Field, make_body, reward, run_episode, start_positions  # noqa: E402

SENSORS = ("ASEL", "ASER")


def brain_for(r, lesion=()):
    cfg = load_config("configs/connectome.yaml")
    cfg["signs"]["glutamate"] = r["glutamate"]
    conn = make_condition(build_connectome(cfg), r["condition"], r["seed"])
    bc = BrainConfig(bounded=r.get("bounded", False), activation=r.get("activation", "sigmoid"),
                     lesion=tuple(lesion))  # fmt: skip
    return Brain(conn, bc)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--results", default="reports/chemotaxis_pilot_tanh")
    p.add_argument("--config", default="configs/chemotaxis.yaml")
    p.add_argument("--panels", type=int, default=6, help="most paths figures to draw")
    args = p.parse_args()
    out = Path(args.results)
    if (out / "runs").is_dir():  # one file per finished run (works on partial studies)
        results = [json.loads(f.read_text()) for f in sorted((out / "runs").glob("*.json"))]
    else:
        results = json.loads((out / "results.json").read_text())

    run_cfg = load_run_config(args.config)
    env = env_config(run_cfg["env"], run_cfg["env_overrides"])
    field = Field(env["field"])
    ev = run_cfg["evaluation"]
    head, heading = start_positions(env["start"], field, ev["n_starts"], ev["test_seed"])
    body = make_body(env["body"])
    gain_cfg = env["reward"] | {"energy_weight": 0.0, "idle_penalty": 0.0}

    # draw the best run of each graph first, then the rest, up to --panels
    ranked = sorted(results, key=lambda r: -r["test"]["gaussian"]["brain"]["reward_mean"])
    firsts = list({r["condition"]: r for r in reversed(ranked)}.values())
    shown = (firsts + [r for r in ranked if r not in firsts])[: args.panels]
    fig, axes = plt.subplots(2, len(shown), figsize=(4 * len(shown), 8), squeeze=False)
    g = np.linspace(-8, 8, 160)
    xx, yy = np.meshgrid(g, g)
    conc = field.conc(np.stack([xx, yy], -1))
    rows = []
    for r in results:
        col = shown.index(r) if r in shown else None
        x = np.repeat(np.array(r["x"])[None], len(heading), 0)
        stats = {}
        for row, (label, lesion) in enumerate([("intact", ()), ("ASEL+ASER silenced", SENSORS)]):
            ep = run_episode(BrainController(brain_for(r, lesion), x), field, head, heading,
                             body=body, **env["episode"])  # fmt: skip
            gain = reward(ep, field, gain_cfg)
            dist = np.linalg.norm(ep.centroid[-1] - field.center, axis=1)
            stats[label] = (gain.mean(), (gain > 0).mean(), dist.mean())
            if col is None:
                continue
            ax = axes[row, col]
            ax.contourf(xx, yy, conc, levels=15, cmap="Greens")
            for k in range(12):
                ax.plot(*ep.centroid[:, k].T, lw=0.8, color="C0" if row == 0 else "C3")
            ax.plot(*head[:12].T, "k.", ms=3)
            ax.set_aspect("equal")
            ax.set_xlim(-8, 8)
            ax.set_ylim(-8, 8)
            ax.set_title(f"{r['run']}\n{label}: final distance {dist.mean():.1f} mm", fontsize=8)
        a, b = stats["intact"], stats["ASEL+ASER silenced"]
        rows.append(f"| {r['run']} | {a[0]:+.3f} | {a[1]:.0%} | {a[2]:.2f} "
                    f"| {b[0]:+.3f} | {b[1]:.0%} | {b[2]:.2f} |")  # fmt: skip
    fig.tight_layout()
    fig.savefig(out / "trajectories.png", dpi=100)
    lines = [
        "# Do trained worms use their salt sensors?",
        "",
        f"Generated by `scripts/chemotaxis_figure.py --results {args.results}`. Test starts "
        f"({len(heading)}) in the training arena; the same trained parameters with ASEL and "
        "ASER silenced. Concentration gain leaves out the energy and idle penalties.",
        "",
        "| run | gain, intact | climbed, intact | final distance (mm), intact "
        "| gain, sensors silenced | climbed, silenced | final distance (mm), silenced |",
        "|---|---|---|---|---|---|---|",
        *rows,
        "",
        "![paths](trajectories.png)",
        "",
    ]
    (out / "sensor_lesion.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
