"""Why does a food-plus-energy reward not produce straight crawling in our arena?

    uv run python scripts/why_circling.py

Three checks, written to reports/why_circling.md:

1. Energy: does crawling in circles cost more than crawling straight? Hand-coded gaits
   with increasing turning bias: power, speed, and energy per mm of net progress.
2. Sensing range: at what distance from the food is the salt gradient still felt?
   The salt neurons respond to the relative change (c - c_avg) / (conc_ref + c_avg);
   for a worm crawling straight towards the food at 0.18 mm/s this is the signal per
   second, against the arena's distances.
3. Where trained circlers circle: turning per mm of progress as a function of the
   distance from the food, for the overnight brains (circlers and straight crawlers).
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from wormbrain.brain import BrainConfig, BrainController
from wormbrain.controllers import TravelingWave
from wormbrain.env import Field, progress_speed, run_episode, start_positions
from wormbrain.export import build_brain
from wormbrain.locomotion import FLAT

OUT = Path("reports/why_circling.md")


def energy_table():
    rows = []
    for bias in (0.0, 0.1, 0.2, 0.3):
        ep = run_episode(TravelingWave(bias=bias), FLAT, np.zeros((1, 2)), np.zeros(1),
                         duration=60.0, dt=0.02)  # fmt: skip
        power = ep.power[50:].mean()
        path = np.linalg.norm(np.diff(ep.centroid[50:, 0], axis=0), axis=-1).sum() / (
            ep.t[-1] - ep.t[50]
        )
        prog = progress_speed(ep)[0]
        rows.append(f"| {bias:.1f} | {power:.3f} | {path:.3f} | {prog:.3f} "
                    f"| {power / max(path, 1e-9):.3f} | {power / max(prog, 1e-9):.3f} |")  # fmt: skip
    return rows


def sensing_table(sigma=4.0, speed=0.18, tau=3.0):
    """Relative change seen over ``tau`` seconds while heading straight for the food."""
    conc_ref = BrainConfig().conc_ref
    rows = []
    for d in (2, 4, 6, 8, 10, 12, 14):
        c = np.exp(-(d**2) / (2 * sigma**2))
        c_ahead = np.exp(-((d - speed * tau) ** 2) / (2 * sigma**2))
        rel = (c_ahead - c) / (conc_ref + c)
        rows.append(f"| {d} | {c:.4f} | {rel:.3f} |")
    return rows


def curvature_by_distance(run, field, bins=(0, 1, 2, 4, 6, 10)):
    brain, x = build_brain(run), np.array(run["x"])
    head, heading = start_positions({"distance": [4.0, 8.0]}, field, 32, seed=4242)
    ep = run_episode(BrainController(brain, np.repeat(x[None], 32, 0)), field, head, heading,
                     duration=150.0, dt=0.02)  # fmt: skip
    k = 10  # 2 s windows at 0.2 s per record
    d = ep.centroid[k:] - ep.centroid[:-k]
    ang = np.unwrap(np.arctan2(d[..., 1], d[..., 0]), axis=0)
    signed = np.diff(ang, axis=0)  # radians per record step, per worm
    step = np.linalg.norm(np.diff(ep.centroid[k:], axis=0), axis=-1)
    dist = np.linalg.norm(ep.centroid[k + 1 :] - field.center, axis=-1)
    out = []
    for lo, hi in zip(bins[:-1], bins[1:], strict=True):
        m = (dist >= lo) & (dist < hi)
        if m.sum() <= 20:
            out.append((np.nan, np.nan))
            continue
        total = np.abs(signed[m]).sum()
        # one-way share: |net signed turning| / total turning, per worm, averaged by time
        one_way = sum(abs(signed[:, w][m[:, w]].sum()) for w in range(m.shape[1])) / total
        out.append((np.rad2deg(total) / max(step[m].sum(), 1e-9), one_way))
    return out


def main():
    field = Field({"type": "gaussian", "peak": [0.0, 0.0], "sigma": 4.0})
    lines = ["# Why do trained worms circle?", "",
             "Generated by `scripts/why_circling.py`.", "",
             "## 1. Circling costs almost no extra energy", "",
             "Hand-coded 0.4 Hz wave with a constant turning bias, 60 s on a flat field. "
             "Power is the drag dissipated by the body (the model's energy cost).", "",
             "| turning bias | power | path speed (mm/s) | net progress (mm/s) "
             "| energy per mm of path | energy per mm of net progress |",
             "|---|---|---|---|---|---|", *energy_table(), "",
             "Energy per mm *crawled* barely changes with turning; only energy per mm of *net "
             "progress* rises, because a circling worm goes nowhere. So an energy cost only "
             "punishes circling if getting somewhere matters.", "",
             "## 2. The food can be smelled from anywhere in the arena", "",
             "Salt neurons respond to relative change, (c − c_avg) / (0.05 + c_avg). Signal "
             "over 3 s for a worm heading straight at the food at 0.18 mm/s (Gaussian food, "
             "σ = 4 mm). Training starts 3–8 mm from the food:", "",
             "| distance (mm) | concentration | relative change in 3 s |", "|---|---|---|",
             *sensing_table(), ""]  # fmt: skip

    rows = []
    for folder, label in [("reports/natural_far/runs", "E. far food"),
                          ("reports/natural_fast/runs", "A. fast approach")]:  # fmt: skip
        for name in ("real_glu-excitatory_seed1", "real_glu-inhibitory_seed0",
                     "real_glu-inhibitory_seed1"):  # fmt: skip
            run = json.loads((Path(folder) / f"{name}.json").read_text())
            c = curvature_by_distance(run, field)
            rows.append(f"| {label} | {name} | " + " | ".join(
                "—" if np.isnan(t) else f"{t:.0f} ({w:.0%})" for t, w in c) + " |")  # fmt: skip
    lines += ["## 3. Where the worms turn, and whether it is one-way (circling)", "",
              "Turning per mm of crawling (°/mm) by distance from the food, and in brackets "
              "the share of it that goes one way (100% = circling; near 0 = weaving left "
              "and right). 32 starts 4–8 mm away, 150 s:", "",
              "| scenario | run | 0–1 mm | 1–2 mm | 2–4 mm | 4–6 mm | 6–10 mm |",
              "|---|---|---|---|---|---|---|", *rows, ""]  # fmt: skip
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
