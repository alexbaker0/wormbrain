"""Does the chemotaxis reward separate steering from not steering, beyond noise?

    uv run python scripts/reward_check.py [--config configs/chemotaxis.yaml]

Scores hand-coded behaviours on 64 starts in the training arena and compares the
gaps between them with the noise of one training evaluation (a mean over
``stage2.n_starts`` random starts). Writes reports/reward_check.md.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from wormbrain.chemotaxis import env_config, load_run_config
from wormbrain.controllers import GradientSteering, TravelingWave
from wormbrain.env import (
    Field,
    mean_curvature,
    mean_turning_rate,
    path_speed,
    reward,
    run_episode,
    start_positions,
)
from wormbrain.locomotion import FLAT


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--config", default="configs/chemotaxis.yaml")
    p.add_argument("--starts", type=int, default=64)
    p.add_argument("--out", default="reports/reward_check.md")
    args = p.parse_args()
    OUT = Path(args.out)

    cfg = load_run_config(args.config)
    env = env_config(cfg["env"], cfg["env_overrides"])
    field = Field(env["field"])
    head, heading = start_positions(env["start"], field, args.starts, seed=2000)
    k = cfg["stage2"]["n_starts"]
    behaviours = {
        "frozen (no muscle activity)": TravelingWave(amplitude=0.0),
        "blind crawling": TravelingWave(),
        "circling (constant turn)": TravelingWave(bias=0.3),
        "slow wide circling": TravelingWave(frequency=0.2, bias=0.1),
        "hand-coded steering": GradientSteering(),
    }
    st = cfg.get("straightness")
    rows, scores = [], {}
    for name, ctrl in behaviours.items():
        ep = run_episode(ctrl, field, head, heading, **env["episode"])
        r = reward(ep, field, env["reward"])
        turn = 0.0
        if st:  # same penalty as training: turning on a flat field above the threshold
            hd = np.random.default_rng(0).uniform(0, 2 * np.pi, st["n_headings"])
            flat = run_episode(ctrl, FLAT, np.zeros((len(hd), 2)), hd,
                               duration=st["duration"], dt=st["dt"])  # fmt: skip
            if st.get("measure") == "per_mm":
                turn = float(mean_curvature(flat).mean())
                r = r - st["weight"] * max(0.0, turn - st["threshold_deg_mm"])
            else:
                turn = float(np.abs(mean_turning_rate(flat)).mean())
                r = r - st["weight"] * max(0.0, turn - st["threshold_deg_s"])
        scores[name] = r
        rows.append(
            f"| {name} | {r.mean():+.3f} | {r.std(ddof=1):.3f} | {r.std(ddof=1) / np.sqrt(k):.3f} "
            f"| {path_speed(ep).mean():.3f} | {ep.power[1:].mean():.3f} | {turn:.0f} |"
        )
    steer = scores["hand-coded steering"]
    gaps = []
    for name in [b for b in behaviours if b != "hand-coded steering"]:
        other = scores[name]
        diff = steer - other  # same starts, so paired
        noise = diff.std(ddof=1) / np.sqrt(k)
        gaps.append(f"| steering − {name} | {diff.mean():+.3f} | {noise:.3f} "
                    f"| {diff.mean() / noise:.1f} |")  # fmt: skip
    ep_cfg = env["episode"]
    lines = [
        "# Reward check",
        "",
        f"Generated by `scripts/reward_check.py --config {args.config}`: {args.starts} starts "
        f"{env['start']['distance'][0]:g}–{env['start']['distance'][1]:g} mm from food, "
        f"{ep_cfg['duration']:g} s episodes at dt = {ep_cfg['dt']:g} s. Reward settings: "
        f"`{env['reward']}`." + (f" Straightness penalty: `{st}`." if st else ""),
        "",
        f"| behaviour | reward mean | SD over starts | noise of a {k}-start mean "
        "| path speed (mm/s) | power | flat-field turning (deg/s, or deg/mm if per_mm) |",
        "|---|---|---|---|---|---|---|",
        *rows,
        "",
        f"Gap between steering and each alternative on the same starts, against the noise "
        f"of one {k}-start training evaluation (> 2 means a single evaluation usually "
        "ranks them correctly):",
        "",
        "| comparison | mean gap | noise | gap / noise |",
        "|---|---|---|---|",
        *gaps,
        "",
    ]
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
