"""Does a salt signal reach the motor neurons? Bounded vs unbounded random brains.

    uv run python scripts/sensory_reach.py

Draws random parameter vectors around the starting point, runs each brain for
10 s without a body (no curvature input) with and without ASEL clamped on, and
measures how many neurons change their transmitter release, how much the head
motor neurons change, and how much the dorsal-minus-ventral muscle balance moves.
Writes reports/sensory_reach.md.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from wormbrain.brain import ACTIVATION, Brain, BrainConfig, BrainController
from wormbrain.connectome import build_connectome, load_config

OUT = Path("reports/sensory_reach.md")
HEAD_MOTOR = ("RMD", "SMD", "SMB", "RIA", "RMF", "RMH")


def responses(brain, x, clamp, steps=500, dt=0.02):
    ctrl = BrainController(brain, x)
    n = len(x)
    ctrl.reset(n)
    obs = {"t": 0.0, "conc": np.ones(n), "kappa": np.zeros((n, 15))}
    base_input = ctrl.sensory_input
    ctrl.sensory_input = lambda o, d: base_input(o, d) + clamp
    for _ in range(steps):
        muscle = ctrl.step(obs, dt)
    release = ACTIVATION[brain.cfg.activation](ctrl.p["gain"] * ctrl.v)
    dv = muscle[:, :2].mean((1, 2)) - muscle[:, 2:].mean((1, 2))
    return release, dv


def main():
    conn = build_connectome(load_config("configs/connectome.yaml"))
    head = np.array([c in HEAD_MOTOR for c in conn.cell_class])
    rows = []
    settings = [(False, "per_neuron", "sigmoid"), (True, "per_neuron", "sigmoid"),
                (True, "global", "sigmoid"), (True, "unit_loop_gain", "sigmoid"),
                (True, "per_neuron", "tanh"), (True, "unit_loop_gain", "tanh")]  # fmt: skip
    for bounded, normalise, activation in settings:
        cfg = BrainConfig(bounded=bounded, normalise=normalise, activation=activation)
        brain = Brain(conn, cfg)
        for spread in (0.5, 2.0):
            rng = np.random.default_rng(0)
            x = brain.spec.x0() + rng.normal(0, spread, (64, brain.n_params))
            clamp = np.zeros((64, brain.n))
            clamp[:, brain.on_idx] = 3.0
            r0, dv0 = responses(brain, x, 0.0)
            r1, dv1 = responses(brain, x, clamp)
            delta = np.abs(r1 - r0)
            rows.append(
                f"| {'bounded' if bounded else 'unbounded'}, {normalise.replace('_', ' ')}, "
                f"{activation} "
                f"| {spread:g} "
                f"| {np.median((delta > 0.01).sum(1)):.0f} "
                f"| {np.mean((delta[:, head] > 0.01).any(1)):.0%} "
                f"| {np.median(delta[:, head].max(1)):.3f} "
                f"| {np.median(np.abs(dv1 - dv0)):.4f} |"
            )
    lines = [
        "# Does the salt signal reach the motor neurons?",
        "",
        "Generated by `scripts/sensory_reach.py`. 64 random brains per row (starting point "
        "plus Gaussian noise of the given spread on every raw parameter), run for 10 s "
        "without a body, with and without ASEL driven by +3. Medians over brains.",
        "",
        "| parameters, input scaling, activation | spread | neurons whose release changes > 0.01 "
        "| brains where a head motor neuron changes > 0.01 "
        "| largest head-motor change | dorsal−ventral muscle shift |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        f"Head motor classes: {', '.join(HEAD_MOTOR)}. For scale, the hand-coded steering "
        "rule shifts the dorsal−ventral muscle balance by 0.4.",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
