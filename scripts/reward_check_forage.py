"""Does the foraging objective rank behaviours the way we expect, before any training?

    uv run python scripts/reward_check_forage.py

Scores fixed movers and already-trained brains in the serial-foraging world
(configs/forage.yaml: food eaten + approach - 0.2 x energy, 240 s, 16 starts), with no
training. Writes reports/reward_check_forage.md.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from wormbrain.brain import BrainController
from wormbrain.chemotaxis import env_config, load_run_config
from wormbrain.controllers import GradientSteering, TravelingWave
from wormbrain.env import (
    make_body,
    make_field,
    mean_curvature,
    reward,
    run_episode,
    start_positions,
)
from wormbrain.export import build_brain
from wormbrain.locomotion import FLAT

BRAINS = [
    ("old gradient stage: circler that reaches food", "reports/curr_sym_grad/runs/real_glu-excitatory_seed0.json"),
    ("old gradient stage: weak steerer", "reports/curr_sym_grad/runs/real_glu-inhibitory_seed0.json"),
    ("old curriculum, after patch world: straight forager", "reports/curr_sym_patch/runs/real_glu-excitatory_seed0.json"),
    ("old curriculum, after patch world: looping forager", "reports/curr_sym_patch/runs/real_glu-inhibitory_seed1.json"),
    ("symmetric body, no curriculum: straight but blind", "reports/patches_sym/runs/real_glu-inhibitory_seed0.json"),
]  # fmt: skip


class Frozen:
    def reset(self, n):
        self.n = n

    def step(self, obs, dt):
        return np.full((self.n, 4, 24), 0.5)


def main():
    cfg = load_run_config("configs/forage.yaml")
    env = env_config(cfg["env"], cfg["env_overrides"])
    body, field, n = make_body(env["body"]), make_field(env["field"]), 16
    head, heading = start_positions(env["start"], field, n, seed=123)
    movers = [("frozen", lambda m: Frozen()), ("blind straight crawling", lambda m: TravelingWave()),
              ("blind circling (bias 0.3)", lambda m: TravelingWave(bias=0.3)),
              ("hand-coded steering", lambda m: GradientSteering())]  # fmt: skip
    for label, path in BRAINS:
        run = json.loads(Path(path).read_text())
        b, x = build_brain(run), np.array(run["x"])
        movers.append((label, lambda m, b=b, x=x: BrainController(b, np.repeat(x[None], m, 0))))
    lines = ["# Foraging objective: does it rank behaviours as expected?", "",
             "Generated by `scripts/reward_check_forage.py`; no training involved. Score = food "
             "eaten + closest approach to the unfinished food − 0.2 × energy, over "
             f"{env['episode']['duration']:g} s and {n} starts.", "",
             "| mover | score | foods eaten | energy | turning on an empty field (°/mm) |",
             "|---|---|---|---|---|"]  # fmt: skip
    for label, make in movers:
        ep = run_episode(make(n), field, head, heading, body=body, **env["episode"])
        r = reward(ep, field, env["reward"]).mean()
        flat = run_episode(make(4), FLAT, np.zeros((4, 2)), np.arange(4) * 1.5, duration=60.0,
                           dt=0.02, body=body)  # fmt: skip
        lines.append(f"| {label} | {r:+.2f} | {ep.eaten[-1].mean():.2f} | {ep.power[1:].mean():.2f} "
                     f"| {mean_curvature(flat).mean():.0f} |")  # fmt: skip
        print(lines[-1], flush=True)
    Path("reports/reward_check_forage.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
