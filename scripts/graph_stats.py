"""Graph statistics of the real connectome next to its controls.

    uv run python scripts/graph_stats.py [--config configs/connectome.yaml] [--seeds 10]

Writes reports/graph_stats/{graph_stats.md, graph_stats.json, degrees.png, adjacency.png}.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from wormbrain.connectome import build_connectome, load_config, sign_rules  # noqa: E402
from wormbrain.controls import CONDITIONS, make_condition  # noqa: E402
from wormbrain.graphstats import stats  # noqa: E402

OUT = Path("reports/graph_stats")
ROLE_ORDER = ["sensory", "inter", "motor", "other"]


def summarise(rows: list[dict]) -> dict:
    out = {}
    for key, value in rows[0].items():
        if isinstance(value, str):
            out[key] = sorted({r[key] for r in rows})
            out[key] = out[key][0] if len(out[key]) == 1 else ", ".join(out[key])
        else:
            v = np.array([r[key] for r in rows], dtype=float)
            out[key] = {"mean": float(v.mean()), "sd": float(v.std())}
    return out


def fmt(cell) -> str:
    if isinstance(cell, str):
        return cell
    if isinstance(cell, dict):
        if cell["sd"] <= 1e-9 * max(1.0, abs(cell["mean"])):
            return fmt(cell["mean"])
        return f"{cell['mean']:.3g} ± {cell['sd']:.2g}"
    if float(cell).is_integer():
        return str(int(cell))
    return f"{cell:.3g}"


def degree_figure(real, controls, path):
    fig, axes = plt.subplots(1, 3, figsize=(12, 3.4))
    panels = [
        ("chemical in-degree", lambda c: (c.chem > 0).sum(0)),
        ("chemical out-degree", lambda c: (c.chem > 0).sum(1)),
        ("gap-junction degree", lambda c: (c.gap > 0).sum(1)),
    ]
    for ax, (title, f) in zip(axes, panels, strict=True):
        top = max(f(c).max() for c in [real, *sum(controls.values(), [])]) + 1
        bins = np.arange(0, top + 2, 2)
        for name, conns in controls.items():
            ax.hist(np.concatenate([f(c) for c in conns]), bins=bins, density=True,
                    histtype="step", lw=1.5, label=f"{name} ({len(conns)} seeds)")  # fmt: skip
        ax.hist(f(real), bins=bins, density=True, color="0.3", alpha=0.35, label="real")
        ax.set_title(title)
        ax.set_xlabel("degree")
    axes[0].set_ylabel("fraction of neurons")
    axes[-1].legend(frameon=False, fontsize=8)
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def adjacency_figure(conn, path):
    order = sorted(range(conn.n), key=lambda k: (ROLE_ORDER.index(conn.role[k]), conn.neurons[k]))
    signed = (conn.chem * conn.chem_sign)[np.ix_(order, order)]
    fig, axes = plt.subplots(1, 2, figsize=(11, 5.2))
    lim = np.percentile(np.abs(signed[signed != 0]), 95)
    axes[0].imshow(signed, cmap="RdBu_r", vmin=-lim, vmax=lim, interpolation="nearest")
    axes[0].set_title("chemical synapses (red excitatory, blue inhibitory)")
    axes[1].imshow(np.log1p(conn.gap[np.ix_(order, order)]), cmap="Greys", interpolation="nearest")
    axes[1].set_title("gap junctions (log weight)")
    roles = [conn.role[k] for k in order]
    edges = [roles.index(r) for r in ROLE_ORDER if r in roles][1:]
    for ax in axes:
        for e in edges:
            ax.axhline(e - 0.5, color="k", lw=0.5)
            ax.axvline(e - 0.5, color="k", lw=0.5)
        ax.set_xlabel("postsynaptic (sensory | inter | motor | other)")
        ax.set_ylabel("presynaptic")
        ax.set_xticks([])
        ax.set_yticks([])
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--config", default="configs/connectome.yaml")
    p.add_argument("--seeds", type=int, default=10)
    args = p.parse_args()

    cfg = load_config(args.config)
    real = build_connectome(cfg)
    controls = {c: [make_condition(real, c, s) for s in range(args.seeds)] for c in CONDITIONS[1:]}
    table = {"real": stats(real)} | {
        c: summarise([stats(x) for x in v]) for c, v in controls.items()
    }
    rules = sign_rules(cfg)
    rule_counts = {}
    for n in real.neurons:
        rule_counts[rules[n]] = rule_counts.get(rules[n], 0) + 1

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "graph_stats.json").write_text(
        json.dumps({"config": cfg, "seeds": args.seeds, "stats": table}, indent=1)
    )
    degree_figure(real, {c: controls[c] for c in ("rewired", "random")}, OUT / "degrees.png")
    adjacency_figure(real, OUT / "adjacency.png")

    lines = [
        "# Graph statistics",
        "",
        f"Generated by `scripts/graph_stats.py --config {args.config} --seeds {args.seeds}`.",
        "Controls show mean ± SD over seeds. Hops count the shortest path from each sensory",
        "neuron to its nearest motor neuron, chemical synapses forwards, gap junctions both ways.",
        "",
        "| statistic | " + " | ".join(table) + " |",
        "|---|" + "---|" * len(table),
    ]
    for key in table["real"]:
        lines.append(f"| {key} | " + " | ".join(fmt(table[c][key]) for c in table) + " |")
    lines += ["", "## Sign rule per neuron (real graph)", "", "| rule | neurons |", "|---|---|"]
    lines += [f"| {r} | {k} |" for r, k in sorted(rule_counts.items(), key=lambda x: -x[1])]
    lines += ["", "![degree distributions](degrees.png)", "", "![adjacency](adjacency.png)", ""]
    (OUT / "graph_stats.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
